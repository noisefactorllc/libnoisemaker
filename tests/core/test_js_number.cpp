void check_trig_and_log() {
    namespace js = libnoisemaker::js;
    for (const auto& c : kTrigCases) {
        NM_CHECK(same_bits(js::sin(c.x), c.sin));
        NM_CHECK(same_bits(js::cos(c.x), c.cos));
    }
    for (const auto& c : kLogCases) NM_CHECK(same_bits(js::log(c.x), c.log));
}

void check_parse_float() {
    for (const auto& c : kParseFloatCases) {
        const bool same = same_bits(libnoisemaker::js::parseFloat(c.text), c.bits);
        if (!same) std::fprintf(stderr, "parseFloat(\"%s\") differs\n", libnoisemaker::js_to_utf8(c.text).c_str());
        NM_CHECK(same);
    }
}

void check_math() {
    namespace js = libnoisemaker::js;
    for (const auto& c : kRoundCases) NM_CHECK(same_bits(js::round(c.input), c.bits));
    for (const auto& c : kBinaryCases) {
        NM_CHECK(same_bits(js::max(c.a, c.b), c.max));
        NM_CHECK(same_bits(js::min(c.a, c.b), c.min));
        NM_CHECK(same_bits(js::pow(c.a, c.b), c.pow));
    }
}

void check_string_to_number() {
    for (const auto& c : kStringCases) {
        const double value = libnoisemaker::js::stringToNumber(c.text);
        uint64_t bits = 0;
        std::memcpy(&bits, &value, sizeof bits);
        const bool expected_nan = (c.bits & 0x7ff0000000000000ull) == 0x7ff0000000000000ull && (c.bits & 0xfffffffffffffull);
        const bool same = expected_nan ? std::isnan(value) : bits == c.bits;
        if (!same) {
            std::fprintf(stderr, "stringToNumber(\"%s\"): expected %016llx, got %016llx\n",
                         libnoisemaker::js_to_utf8(c.text).substr(0, 40).c_str(),
                         static_cast<unsigned long long>(c.bits), static_cast<unsigned long long>(bits));
        }
        NM_CHECK(same);
    }
}
